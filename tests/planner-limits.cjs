const assert = require("node:assert/strict"), fs = require("node:fs"), path = require("node:path"), vm = require("node:vm");
const scope = { hakoAfFeatureNames: {}, hakoAfSkillIdentity: {} };
vm.createContext(scope);
const source = fs.readFileSync(path.join(__dirname, "../extension/training-planner.js"), "utf8");
vm.runInContext(source.replace("globalThis.hakoAfTrainingPlanner = { start };", "globalThis.skillUsage = skillUsage;"), scope);
const plain = value => JSON.parse(JSON.stringify(value)), items = size => Array.from({ length: size }, (_, i) => ({ name: "スキル" + (i + 1) }));
const twelve = items(12);
let result = plain(scope.skillUsage(twelve, 10, () => false));
assert.equal(result.used, 12);assert.equal(result.extra, 2);
assert.deepEqual(result.overflow, [...Array(10).fill(false), true, true]);
twelve[2].reserved = true;
result = plain(scope.skillUsage(twelve, 10, skill => !!skill.reserved));
assert.equal(result.used, 11);assert.deepEqual(result.overflow, [...Array(11).fill(false), true]);
twelve[4] = { name: "R6固有", unique: "rank6", passive: true };
result = plain(scope.skillUsage(twelve, 10, skill => !!skill.reserved));
assert.equal(result.used, 10);assert.equal(result.extra, 0);assert.ok(result.overflow.every(value => !value));
assert.equal(scope.skillUsage(items(27), 26, () => false).extra, 1);
assert.equal(scope.skillUsage(items(27), 27, () => false).extra, 0);
assert.equal(scope.skillUsage(items(37), 10, () => true).extra, 0);
assert.deepEqual(plain(scope.skillUsage([], 10, () => false)), { used: 0, extra: 0, overflow: [] });
console.log("Planner limits: trailing overflow, reserves, free R6 passives, Rank 6/7 and empty plans passed.");
